"""SMHI radar."""

from __future__ import annotations

import asyncio
from datetime import UTC, datetime
from functools import cache
from importlib.resources import files
from io import BytesIO
from math import atan, atanh, cos, cosh, radians, sin, sinh, tan
from typing import Any, TypedDict, cast

from aiohttp import ClientSession
from PIL import Image, ImageDraw, TiffImagePlugin

from .const import API_RADAR, LOGGER
from .exceptions import SMHIError, SmhiRadarException
from .smhi import SmhiAPI

# GeoTIFF pixel values
NO_ECHO = 0
NO_DATA = 255
GAIN = 0.4
OFFSET = -30.0
# Reflectivities below 5 dBZ are usually not precipitation, e.g. birds or insects
MIN_PRECIPITATION_DBZ = 5.0

# GeoTIFF tags
MODEL_PIXEL_SCALE = 33550
MODEL_TIEPOINT = 33922

# Grid of the radar images in SWEREF99 TM, used for the background map
RADAR_SIZE = (471, 887)
RADAR_ORIGIN = (126648.404, 7771252.876)  # Top left corner in metres
RADAR_PIXEL_SIZE = (2014.9581656050955, 2014.9581657271704)  # Metres

# Background map of the radar grid at BASEMAP_SCALE times the radar resolution,
# generated by script/generate_radar_basemap.py
BASEMAP = "radar_basemap.png"
BASEMAP_SCALE = 2
MARKER_RADIUS = 7
MARKER_COLOR = (220, 0, 0, 255)
MARKER_OUTLINE = (255, 255, 255, 255)

# SWEREF99 TM on the GRS 80 ellipsoid
GRS80_SEMI_MAJOR_AXIS = 6378137.0
GRS80_FLATTENING = 1 / 298.257222101
SWEREF99TM_CENTRAL_MERIDIAN = 15.0
SWEREF99TM_SCALE = 0.9996
SWEREF99TM_FALSE_EASTING = 500000.0


class SMHIRadar(TypedDict):
    """SMHI radar at a location.

    https://opendata.smhi.se/radar/data
    """

    valid_time: datetime
    image_url: str  # PNG image of the radar composite for Sweden without a map
    dbz: float | None  # None if no echo or no data
    precipitation: float | None  # mm/h, 0 if no echo, None if no data


class SMHIRadarImage:
    """SMHI Open Data API - Radar.

    https://opendata.smhi.se/radar/introduction
    """

    def __init__(
        self,
        longitude: str,
        latitude: str,
        session: ClientSession | None = None,
    ) -> None:
        """Init the SMHI radar."""
        self._longitude = str(round(float(longitude), 6))
        self._latitude = str(round(float(latitude), 6))
        self._api = SmhiAPI(session)

    async def async_get_radar(self) -> SMHIRadar:
        """Return the latest radar image and the precipitation at the location."""
        LOGGER.debug("Getting radar")
        try:
            json_data = await self._api.async_get_data(API_RADAR)
            valid_time, links = _latest_files(json_data)
            image = await self._api.async_get_bytes(links["tif"])
        except SMHIError as error:
            LOGGER.debug("Error getting radar: %s", str(error))
            raise SmhiRadarException from error
        LOGGER.debug("Got radar valid at %s", valid_time)

        dbz, precipitation = await asyncio.get_running_loop().run_in_executor(
            None,
            get_radar_values,
            image,
            float(self._longitude),
            float(self._latitude),
        )
        return SMHIRadar(
            valid_time=valid_time,
            image_url=links["png"],
            dbz=dbz,
            precipitation=precipitation,
        )

    async def async_get_image(self) -> bytes:
        """Return the latest radar image of Sweden on a map as PNG.

        The location is marked with a red dot.
        """
        LOGGER.debug("Getting radar image")
        try:
            json_data = await self._api.async_get_data(API_RADAR)
            _, links = _latest_files(json_data)
            image = await self._api.async_get_bytes(links["png"])
        except SMHIError as error:
            LOGGER.debug("Error getting radar image: %s", str(error))
            raise SmhiRadarException from error

        return await asyncio.get_running_loop().run_in_executor(
            None,
            get_map_image,
            image,
            float(self._longitude),
            float(self._latitude),
        )


def _latest_files(data: dict[str, Any]) -> tuple[datetime, dict[str, str]]:
    """Return the valid time and the links by format for the latest image.

    The latest files are given both as PNG and GeoTIFF, and separately as H5.
    """
    for file in data["lastFiles"]:
        links = {
            file_format["key"]: file_format["link"] for file_format in file["formats"]
        }
        if "png" in links and "tif" in links:
            valid_time = datetime.strptime(file["valid"], "%Y-%m-%d %H:%M").replace(
                tzinfo=UTC
            )
            return valid_time, links
    raise SmhiRadarException("No latest radar image in data")


def get_radar_values(
    image: bytes, longitude: float, latitude: float
) -> tuple[float | None, float | None]:
    """Get the dBZ and the precipitation in mm/h at a location from a radar GeoTIFF.

    The dBZ is None if there is no echo. Both are None if there is no data or the
    location is outside the image.
    """
    with TiffImagePlugin.TiffImageFile(BytesIO(image)) as tif:
        # The GeoTIFF has one band with 8-bit values
        if tif.mode != "L":
            raise SmhiRadarException(f"Unexpected radar image mode {tif.mode}")
        scale_x, scale_y, _ = tif.tag_v2[MODEL_PIXEL_SCALE]
        _, _, _, origin_x, origin_y, _ = tif.tag_v2[MODEL_TIEPOINT]
        easting, northing = to_sweref99tm(longitude, latitude)
        column = int((easting - origin_x) // scale_x)
        row = int((origin_y - northing) // scale_y)
        if not (0 <= column < tif.width and 0 <= row < tif.height):
            LOGGER.debug("Location is outside the radar image")
            return None, None
        value = cast("int", tif.getpixel((column, row)))

    if value == NO_DATA:
        return None, None
    if value == NO_ECHO:
        return None, 0.0
    dbz = round(value * GAIN + OFFSET, 1)
    return dbz, _precipitation(dbz)


def get_map_image(image: bytes, longitude: float, latitude: float) -> bytes:
    """Return a radar PNG image on the background map with the location marked.

    Returns the radar image as is if it doesn't match the grid of the map.
    """
    with Image.open(BytesIO(image)) as radar:
        if radar.size != RADAR_SIZE:
            LOGGER.warning(
                "Radar image size %s doesn't match the map %s", radar.size, RADAR_SIZE
            )
            return image
        with Image.open(BytesIO(_basemap())) as basemap:
            result = Image.alpha_composite(
                basemap.convert("RGBA"),
                radar.convert("RGBA").resize(basemap.size, Image.Resampling.NEAREST),
            )

    x, y = to_pixel(longitude, latitude, BASEMAP_SCALE)
    ImageDraw.Draw(result).ellipse(
        (x - MARKER_RADIUS, y - MARKER_RADIUS, x + MARKER_RADIUS, y + MARKER_RADIUS),
        fill=MARKER_COLOR,
        outline=MARKER_OUTLINE,
        width=2,
    )
    output = BytesIO()
    result.save(output, format="PNG")
    return output.getvalue()


@cache
def _basemap() -> bytes:
    """Return the background map, read once from the package."""
    return files(__package__).joinpath(BASEMAP).read_bytes()


def to_pixel(
    longitude: float, latitude: float, scale: float = 1
) -> tuple[float, float]:
    """Return the x and y in the radar images for a location.

    Scale gives the pixel for an image scale times the size of the radar images.
    """
    easting, northing = to_sweref99tm(longitude, latitude)
    return (
        (easting - RADAR_ORIGIN[0]) / RADAR_PIXEL_SIZE[0] * scale,
        (RADAR_ORIGIN[1] - northing) / RADAR_PIXEL_SIZE[1] * scale,
    )


def _precipitation(dbz: float) -> float:
    """Return the precipitation in mm/h from the reflectivity in dBZ.

    SMHI uses dBZ = 10 log10(200 R^1.5) with R in mm/h.
    """
    if dbz < MIN_PRECIPITATION_DBZ:
        return 0.0
    return round(float((10 ** (dbz / 10) / 200) ** (1 / 1.5)), 2)


def to_sweref99tm(longitude: float, latitude: float) -> tuple[float, float]:
    """Convert a WGS 84 location to SWEREF99 TM easting and northing in metres.

    Gauss-Krüger projection with the formulas from Lantmäteriet, accurate to
    within a millimetre in Sweden.
    """
    flattening = GRS80_FLATTENING
    e2 = flattening * (2 - flattening)
    n = flattening / (2 - flattening)
    a_roof = GRS80_SEMI_MAJOR_AXIS / (1 + n) * (1 + n**2 / 4 + n**4 / 64)

    a = e2
    b = (5 * e2**2 - e2**3) / 6
    c = (104 * e2**3 - 45 * e2**4) / 120
    d = 1237 * e2**4 / 1260
    beta1 = n / 2 - 2 * n**2 / 3 + 5 * n**3 / 16 + 41 * n**4 / 180
    beta2 = 13 * n**2 / 48 - 3 * n**3 / 5 + 557 * n**4 / 1440
    beta3 = 61 * n**3 / 240 - 103 * n**4 / 140
    beta4 = 49561 * n**4 / 161280

    phi = radians(latitude)
    delta_lambda = radians(longitude - SWEREF99TM_CENTRAL_MERIDIAN)
    sin_phi = sin(phi)
    phi_star = phi - sin_phi * cos(phi) * (
        a + b * sin_phi**2 + c * sin_phi**4 + d * sin_phi**6
    )
    xi = atan(tan(phi_star) / cos(delta_lambda))
    eta = atanh(cos(phi_star) * sin(delta_lambda))

    northing = (
        SWEREF99TM_SCALE
        * a_roof
        * (
            xi
            + beta1 * sin(2 * xi) * cosh(2 * eta)
            + beta2 * sin(4 * xi) * cosh(4 * eta)
            + beta3 * sin(6 * xi) * cosh(6 * eta)
            + beta4 * sin(8 * xi) * cosh(8 * eta)
        )
    )
    easting = (
        SWEREF99TM_SCALE
        * a_roof
        * (
            eta
            + beta1 * cos(2 * xi) * sinh(2 * eta)
            + beta2 * cos(4 * xi) * sinh(4 * eta)
            + beta3 * cos(6 * xi) * sinh(6 * eta)
            + beta4 * cos(8 * xi) * sinh(8 * eta)
        )
        + SWEREF99TM_FALSE_EASTING
    )
    return easting, northing
